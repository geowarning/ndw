/**
 * 获取预警列表（附带级别颜色等信息）
 */
function getAlerts() {
  return ALERTS.map(function (a) {
    const level = LEVELS[a.level];
    return Object.assign({}, a, {
      levelName: level.name,
      color: level.color,
      bg: level.bg
    });
  });
}

/**
 * 按 ID 获取单条预警
 */
function getAlertById(id) {
  const item = getAlerts().find(function (a) {
    return a.id === id;
  });
  return item || null;
}

